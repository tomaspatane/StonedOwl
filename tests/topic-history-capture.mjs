import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile, writeFile, readdir, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { captureAndStoreTopics } from '../scripts/capture-topics-history.mjs';
import { captureAllTopics } from '../sources/caba-topic-capture.js';
const dir = await mkdtemp(join(tmpdir(), 'topic-capture-test-'));
const opts = { directory: join(dir, 'history'), artifactDirectory: join(dir, 'artifact'), outputPath: join(dir, 'report.json') };
const t0 = Date.parse('2026-10-20T12:00:00Z');
const capture = options => captureAllTopics({ ...options, feeds: [{ id: 'test', name: 'Feed', url: 'https://example.test/feed' }] }, async () => new Response('<rss><channel><title>Empty</title></channel></rss>'));
try {
  let r = await captureAndStoreTopics({ ...opts, now: t0, capture });
  assert.equal(r.exitCode, 0); assert.equal(r.report.history.persisted, true);
  assert.equal(r.report.history.baselineReason, 'no_history');
  assert.equal(r.report.snapshotComparisons.basura.eligible, false);
  assert.equal(r.report.topics.transporte.fetchedAt, r.report.fetchedAt, 'All topics share one actual capture clock');
  let envelope = JSON.parse(await readFile(join(opts.artifactDirectory, 'topic-snapshot.json')));
  assert.equal(envelope.format, 'stonedowl-topic-history-v1');
  const explicit = join(dir, 'previous.json'); await writeFile(explicit, JSON.stringify(envelope));
  r = await captureAndStoreTopics({ ...opts, now: t0 + 600000, capture });
  assert.equal(r.report.snapshotComparisons.seguridad.status, 'comparable');
  assert.equal(r.report.snapshotComparisons.seguridad.incidentTrend, 'unknown');
  assert.equal(r.report.history.previousCapturedAt, '2026-10-20T12:00:00.000Z');
  assert.equal((await readdir(opts.directory)).filter(f => f.endsWith('.json')).length, 2, 'Restart retains both immutable captures');
  r = await captureAndStoreTopics({ ...opts, now: t0 + 1200000, capture, previousSnapshotPath: explicit });
  assert.equal(r.report.history.previousCapturedAt, '2026-10-20T12:00:00.000Z', 'Explicit restored baseline is used, not local latest');
  r = await captureAndStoreTopics({ ...opts, now: t0 + 1800000, capture, previousSnapshotPath: join(dir, 'missing.json') });
  assert.equal(r.report.snapshotComparisons.seguridad.eligible, false, 'Restore failure cannot reuse an older local baseline');
  assert.equal(r.report.history.previousCapturedAt, null);
  const failedCapture = options => captureAllTopics({ ...options, feeds: [{ id: 'test', name: 'Feed', url: 'https://example.test/feed' }] }, async () => new Response('Unavailable', { status: 503 }));
  r = await captureAndStoreTopics({ ...opts, now: t0 + 2400000, capture: failedCapture });
  assert.equal(r.exitCode, 1); assert.equal(r.report.history.persisted, true, 'Failures are still history, not discarded');
  r = await captureAndStoreTopics({ ...opts, now: t0 + 3000000, capture });
  assert.equal(r.report.snapshotComparisons.seguridad.eligible, false, 'The previous failed capture is not skipped for a healthy one');
  assert.equal(r.report.history.previousCapturedAt, new Date(t0 + 2400000).toISOString());
  await assert.rejects(captureAndStoreTopics({ ...opts, now: t0 + 3600000, capture: async () => { throw new Error('capture_failure'); } }));
  await assert.rejects(readFile(join(opts.artifactDirectory, 'topic-snapshot.json')), { code: 'ENOENT' }, 'Old artifacts cleared when a new capture fails');
  await assert.rejects(captureAndStoreTopics({ ...opts, capture, previousSnapshotPath: opts.outputPath }), /collision/);
  const retained = join(opts.directory, (await readdir(opts.directory)).find(f => f.endsWith('.json')));
  const before = await readFile(retained, 'utf8');
  await assert.rejects(captureAndStoreTopics({ ...opts, capture, outputPath: retained }), /history_output_path_collision/);
  await assert.rejects(captureAndStoreTopics({ ...opts, capture, artifactDirectory: join(opts.directory, 'nested') }), /history_output_path_collision/);
  const alias = join(dir, 'history-alias'); await symlink(opts.directory, alias);
  await assert.rejects(captureAndStoreTopics({ ...opts, capture, outputPath: join(alias, 'retained.json') }), /history_output_path_collision/);
  assert.equal(await readFile(retained, 'utf8'), before, 'Output cleanup cannot erase immutable history, including via symlinked parents');
  await assert.rejects(captureAndStoreTopics({ ...opts, capture, outputPath: join(opts.artifactDirectory, 'topic-snapshot.json') }), /snapshot_output_path_collision/);
  const readOnlyPath = join(dir, 'not-a-directory'); await writeFile(readOnlyPath, 'file');
  r = await captureAndStoreTopics({ ...opts, directory: readOnlyPath, now: t0 + 4200000, capture });
  assert.equal(r.exitCode, 1); assert.equal(r.report.history.persisted, false);
  assert.equal(r.report.history.reason, 'snapshot_not_saved');
  console.log('Topic capture history: real persistence boundary, restart, explicit baseline, failed capture retention and stale artifact clearing OK');
} finally { await rm(dir, { recursive: true, force: true }); }
