import assert from 'node:assert/strict';
import { captureTopic, captureAllTopics } from '../sources/caba-topic-capture.js';
import worker from '../src/worker.js';
const now = Date.parse('2026-10-20T14:00:00Z');
const feeds = [{ id: 'a', name: 'A', url: 'https://a.test/feed' }, { id: 'b', name: 'B', url: 'https://b.test/feed' }];
const rss = (title = 'Basura acumulada en Almagro', date = 'Tue, 20 Oct 2026 13:00:00 GMT') => `<rss version="2.0"><channel><title>Feed</title><link>https://publisher.test/</link><item><title>${title}</title><link>https://publisher.test/case</link><description>Vecinos de Almagro reclaman contenedores desbordados.</description><pubDate>${date}</pubDate></item></channel></rss>`;
const response = body => new Response(body, { headers: { 'content-type': 'application/rss+xml' } });
const good = await captureTopic('basura', { now, feeds }, async () => response(rss()));
assert.equal(good.ok, true);
assert.equal(good.editorialCases.length, 1);
assert.equal(good.counts.duplicates, 1);
assert.deepEqual(good.radar, []);
assert.equal(good.trend.status, 'unknown');
const partial = await captureTopic('basura', { now, feeds }, async url => url.includes('a.test') ? response(rss()) : new Response('Blocked', { status: 403 }));
assert.equal(partial.ok, false);
assert.equal(partial.captureUsable, true);
assert.equal(partial.coverage.status, 'degraded');
assert.equal(partial.editorialCases.length, 1);
const failed = await captureTopic('basura', { now, feeds }, async () => new Response('<html>Bot challenge</html>', { headers: { 'content-type': 'text/html' } }));
assert.equal(failed.coverage.status, 'failed');
assert.equal(failed.captureUsable, false);
assert.equal(failed.sourceHealth[0].code, 'invalid_rss');
const stale = await captureTopic('basura', { now, feeds }, async () => response(rss('Basura acumulada en Almagro', 'Tue, 01 Sep 2026 13:00:00 GMT')));
assert.equal(stale.coverage.status, 'degraded');
assert.equal(stale.coverage.stale, 2);
assert.equal(stale.editorialCases.length, 0);
const empty = await captureTopic('basura', { now, feeds }, async () => response('<rss><channel><title>Empty</title></channel></rss>'));
assert.equal(empty.ok, true, 'Valid empty feed is distinct from failure');
assert.equal(empty.editorialCases.length, 0);
assert.match(empty.coverage.interpretation, /no cobertura exhaustiva/);
const undated = await captureTopic('basura', { now, feeds }, async () => response(rss('Basura acumulada en Almagro', '')));
assert.equal(undated.coverage.status, 'degraded');
assert.equal(undated.coverage.undated, 2);
const timeout = await captureTopic('basura', { now, feeds, timeoutMs: 5 }, () => new Promise(() => {}));
assert.equal(timeout.coverage.failed, 2);
assert.equal(timeout.sourceHealth[0].code, 'timeout');
await assert.rejects(() => captureTopic('otra', {}), /Tema/);
await assert.rejects(() => captureTopic('basura', { span: '1y' }), /ventana/);
const original = globalThis.fetch;
try {
  globalThis.fetch = async () => response(rss('Basura acumulada en Almagro', new Date().toUTCString()));
  let result = await worker.fetch(new Request('https://app.test/api/basura?span=1w'), {});
  assert.equal(result.status, 200);
  assert.equal((await result.json()).topicId, 'basura');
  result = await worker.fetch(new Request('https://app.test/api/temas'), {});
  assert.deepEqual(Object.keys((await result.json()).topics), ['basura', 'transporte', 'seguridad']);
  assert.equal((await worker.fetch(new Request('https://app.test/api/basura?span=1y'), {})).status, 400);
  assert.equal((await worker.fetch(new Request('https://app.test/api/basura', { method: 'POST' }), {})).status, 405);
  globalThis.fetch = async () => new Response('Unavailable', { status: 503 });
  result = await worker.fetch(new Request('https://app.test/api/seguridad'), {});
  assert.equal(result.status, 503);
  assert.equal((await result.json()).captureHealth.status, 'failed');
  result = await worker.fetch(new Request('https://app.test/api/electricidad'), {});
  const legacy = await result.json();
  assert.equal(legacy.captureHealth.status, 'failed', 'Electricity keeps its own pipeline');
} finally { globalThis.fetch = original; }
let calls = 0;
await captureAllTopics({ now, feeds: [feeds[0]] }, async () => { calls++; await new Promise(resolve => setTimeout(resolve, 1)); return response(rss()); });
assert.equal(calls, 1, 'Shared URLs across topics share an in-flight read but not classification');
console.log('Topic capture and endpoints: live-source errors, stale/empty distinction, dedup, electricity compatibility and read sharing OK');
